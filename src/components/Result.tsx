import { memo } from 'react'
import { TriangleAlertIcon } from 'lucide-react'
import { cn } from '@/lib/utils'
import type { RowResult } from '../engine/types'
import type { MathLive } from '../lib/mathlive'

interface Props {
  mathlive: MathLive
  result: RowResult | undefined
  pending: boolean
}

export const Result = memo(function Result({ mathlive, result, pending }: Props) {
  const content = renderResult(mathlive, result)
  if (!content) return null
  return (
    <div
      className={cn(
        'flex flex-wrap items-center justify-end gap-x-4 gap-y-1 pt-1',
        pending && 'opacity-40 transition-opacity delay-300 duration-300',
      )}
    >
      {content}
    </div>
  )
})

function renderResult(mathlive: MathLive, result: RowResult | undefined) {
  if (!result) return null
  switch (result.kind) {
    case 'empty':
    case 'incomplete':
    case 'defined':
      return null

    case 'timeout':
      return <Warning>Stopped: this took longer than 5 seconds</Warning>

    case 'error':
      return <Warning>{result.message}</Warning>

    case 'value': {
      if (!result.exact && !result.approx && !result.note) return null
      return (
        <>
          {result.note && <span className="text-sm text-muted-foreground">{result.note}</span>}
          {result.exact && (
            <MathValue mathlive={mathlive} prefix={result.bare ? '' : '='} latex={result.exact} />
          )}
          {result.approx && (
            <MathValue mathlive={mathlive} prefix="≈" latex={result.approx} muted />
          )}
        </>
      )
    }
  }
}

function MathValue({
  mathlive,
  prefix,
  latex,
  muted,
}: {
  mathlive: MathLive
  prefix: string
  latex: string
  muted?: boolean
}) {
  const markup = mathlive.convertLatexToMarkup(latex)
  return (
    <div
      className={cn(
        'flex max-w-full items-center gap-2 overflow-x-auto',
        muted ? 'text-muted-foreground' : 'text-foreground',
      )}
    >
      {prefix && <span className="select-none text-lg text-muted-foreground">{prefix}</span>}
      <span
        className="result-math"
        // Markup is generated by MathLive from engine output, not user HTML.
        dangerouslySetInnerHTML={{ __html: markup }}
      />
    </div>
  )
}

function Warning({ children }: { children: React.ReactNode }) {
  return (
    <div className="flex items-center gap-2 text-sm text-amber-700 dark:text-amber-500">
      <TriangleAlertIcon className="size-4 shrink-0" aria-hidden />
      <span>{children}</span>
    </div>
  )
}
